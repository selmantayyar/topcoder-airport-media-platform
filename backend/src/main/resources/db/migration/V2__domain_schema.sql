-- Canonical + platform-owned domain schema (ticket 03).
-- Column/table names are snake_case to match the CamelCaseToUnderscoresNamingStrategy.

CREATE TABLE aircraft_type (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    icao_code       VARCHAR(16) NOT NULL UNIQUE,
    name            VARCHAR(128) NOT NULL,
    seats_economy   INTEGER NOT NULL,
    seats_premium   INTEGER NOT NULL,
    seats_business  INTEGER NOT NULL
);

CREATE TABLE airline (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iata_code  VARCHAR(8) NOT NULL UNIQUE,
    icao_code  VARCHAR(8) NOT NULL,
    name       VARCHAR(128) NOT NULL,
    low_cost   BOOLEAN NOT NULL
);

CREATE TABLE terminal (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acris_id  VARCHAR(128) NOT NULL UNIQUE,
    code      VARCHAR(16) NOT NULL,
    name      VARCHAR(128) NOT NULL
);

CREATE TABLE zone (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acris_id     VARCHAR(128) NOT NULL UNIQUE,
    terminal_id  BIGINT NOT NULL REFERENCES terminal(id),
    name         VARCHAR(128) NOT NULL,
    kind         VARCHAR(32) NOT NULL,
    latitude     DOUBLE PRECISION NOT NULL,
    longitude    DOUBLE PRECISION NOT NULL
);

CREATE TABLE checkpoint (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acris_id  VARCHAR(128) NOT NULL UNIQUE,
    zone_id   BIGINT NOT NULL REFERENCES zone(id),
    name      VARCHAR(128) NOT NULL,
    type      VARCHAR(64) NOT NULL
);

CREATE TABLE queue_measurement (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checkpoint_id               BIGINT NOT NULL REFERENCES checkpoint(id),
    occupancy                   INTEGER NOT NULL,
    wait_time_seconds           INTEGER NOT NULL,
    projected_wait_time_seconds INTEGER NOT NULL,
    throughput                  INTEGER NOT NULL,
    measured_at                 TIMESTAMPTZ NOT NULL
);

CREATE TABLE flight (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number     VARCHAR(16) NOT NULL,
    airline_id        BIGINT NOT NULL REFERENCES airline(id),
    direction         VARCHAR(16) NOT NULL,
    origin            VARCHAR(8) NOT NULL,
    destination       VARCHAR(8) NOT NULL,
    via               VARCHAR(8),
    haul              VARCHAR(16) NOT NULL,
    aircraft_type_id  BIGINT NOT NULL REFERENCES aircraft_type(id),
    pax_count         INTEGER NOT NULL,
    status            VARCHAR(16) NOT NULL,
    delay_minutes     INTEGER NOT NULL,
    delay_code        VARCHAR(16),
    scheduled_time    TIMESTAMPTZ NOT NULL,
    estimated_time    TIMESTAMPTZ,
    actual_time       TIMESTAMPTZ,
    tobt              TIMESTAMPTZ,
    tsat              TIMESTAMPTZ,
    aibt              TIMESTAMPTZ,
    aobt              TIMESTAMPTZ,
    check_in_counters VARCHAR(64),
    belt              VARCHAR(16)
);

CREATE TABLE gate_assignment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id  BIGINT NOT NULL REFERENCES flight(id),
    gate       VARCHAR(16) NOT NULL,
    stand      VARCHAR(16),
    zone_id    BIGINT NOT NULL REFERENCES zone(id)
);

CREATE TABLE flight_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id      BIGINT NOT NULL REFERENCES flight(id),
    type           VARCHAR(32) NOT NULL,
    occurred_at    TIMESTAMPTZ NOT NULL,
    source         VARCHAR(32) NOT NULL,
    message_ref    VARCHAR(128),
    new_gate       VARCHAR(16),
    new_status     VARCHAR(16),
    delay_minutes  INTEGER
);

CREATE TABLE advertiser (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(128) NOT NULL,
    kind  VARCHAR(16) NOT NULL
);

CREATE TABLE outlet (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id  BIGINT NOT NULL REFERENCES advertiser(id),
    name           VARCHAR(128) NOT NULL,
    type           VARCHAR(32) NOT NULL,
    zone_id        BIGINT NOT NULL REFERENCES zone(id)
);

CREATE TABLE screen (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(32) NOT NULL UNIQUE,
    name           VARCHAR(128) NOT NULL,
    zone_id        BIGINT NOT NULL REFERENCES zone(id),
    nearest_gates  VARCHAR(128),
    width_px       INTEGER NOT NULL,
    height_px      INTEGER NOT NULL,
    orientation    VARCHAR(16) NOT NULL,
    status         VARCHAR(16) NOT NULL,
    latency_ms     INTEGER NOT NULL
);

CREATE TABLE campaign (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id            BIGINT NOT NULL REFERENCES advertiser(id),
    name                     VARCHAR(128) NOT NULL,
    status                   VARCHAR(32) NOT NULL,
    budget                   NUMERIC(12, 2) NOT NULL,
    daily_cap                NUMERIC(12, 2),
    frequency_cap_per_screen INTEGER NOT NULL,
    segment_weights_json     TEXT,
    hard_filters_json        TEXT,
    placement_json           TEXT,
    schedule_start           TIMESTAMPTZ NOT NULL,
    schedule_end             TIMESTAMPTZ NOT NULL,
    created_at               TIMESTAMPTZ NOT NULL
);

CREATE TABLE creative (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advertiser_id  BIGINT NOT NULL REFERENCES advertiser(id),
    campaign_id    BIGINT REFERENCES campaign(id),
    name           VARCHAR(128) NOT NULL,
    template_key   VARCHAR(64) NOT NULL,
    language       VARCHAR(8) NOT NULL,
    headline       VARCHAR(256) NOT NULL,
    body           TEXT,
    offer_text     VARCHAR(256)
);

CREATE TABLE promo_code (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id       BIGINT NOT NULL REFERENCES campaign(id),
    code              VARCHAR(32) NOT NULL UNIQUE,
    valid_until       TIMESTAMPTZ NOT NULL,
    linked_flight_id  BIGINT REFERENCES flight(id),
    parent_code       VARCHAR(32),
    redeemed          BOOLEAN NOT NULL
);

CREATE TABLE impression (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id    BIGINT NOT NULL REFERENCES screen(id),
    campaign_id  BIGINT NOT NULL REFERENCES campaign(id),
    shown_at     TIMESTAMPTZ NOT NULL
);

CREATE TABLE redemption (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id    BIGINT NOT NULL REFERENCES campaign(id),
    promo_code_id  BIGINT REFERENCES promo_code(id),
    redeemed_at    TIMESTAMPTZ NOT NULL,
    segment        VARCHAR(32)
);

CREATE INDEX idx_flight_scheduled_time ON flight (scheduled_time);
CREATE INDEX idx_gate_assignment_flight ON gate_assignment (flight_id);
CREATE INDEX idx_impression_campaign ON impression (campaign_id);
CREATE INDEX idx_impression_shown_at ON impression (shown_at);
CREATE INDEX idx_redemption_campaign ON redemption (campaign_id);
CREATE INDEX idx_queue_measurement_checkpoint ON queue_measurement (checkpoint_id);
