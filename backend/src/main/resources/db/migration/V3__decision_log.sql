-- Decision pipeline evidence trail (ticket 06). Every per-screen decision is persisted with
-- its full reasoning so a score can be reproduced and audited from the logged inputs.

CREATE TABLE decision_log (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id          BIGINT NOT NULL REFERENCES screen(id),
    zone_id            BIGINT REFERENCES zone(id),
    decided_at         TIMESTAMPTZ NOT NULL,
    headcount          INTEGER NOT NULL,
    winner_campaign_id BIGINT REFERENCES campaign(id),
    winner_name        VARCHAR(256),
    reason             VARCHAR(512) NOT NULL,
    fallback           BOOLEAN NOT NULL,
    inputs_json        TEXT,
    profile_json       TEXT,
    candidates_json    TEXT NOT NULL
);

CREATE INDEX idx_decision_log_screen ON decision_log (screen_id, decided_at DESC);
CREATE INDEX idx_decision_log_decided_at ON decision_log (decided_at DESC);
CREATE INDEX idx_decision_log_winner ON decision_log (winner_campaign_id);
