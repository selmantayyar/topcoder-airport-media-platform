-- Platform Admin console (ticket 10): when a screen entered its current status (for the
-- "offline > 5 min" incident rule), and the auto-raised incident tracker.

ALTER TABLE screen ADD COLUMN status_changed_at TIMESTAMPTZ;

CREATE TABLE incident (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_key  VARCHAR(128) NOT NULL,
    type         VARCHAR(32) NOT NULL,
    severity     VARCHAR(16) NOT NULL,
    owner        VARCHAR(64) NOT NULL,
    status       VARCHAR(16) NOT NULL,
    title        VARCHAR(256) NOT NULL,
    detail       VARCHAR(512),
    raised_at    TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    resolved_at  TIMESTAMPTZ,
    held         BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_incident_status ON incident (status);
CREATE INDEX idx_incident_subject ON incident (subject_key);
