-- QR-scan funnel step (ticket 08): a passenger opening a promo's claim page, recorded before the
-- redemption so the retailer dashboard can show impressions → scans → redemptions.

CREATE TABLE promo_scan (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id    BIGINT NOT NULL REFERENCES campaign(id),
    promo_code_id  BIGINT REFERENCES promo_code(id),
    scanned_at     TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_promo_scan_campaign ON promo_scan (campaign_id);
CREATE INDEX idx_promo_scan_scanned_at ON promo_scan (scanned_at);
